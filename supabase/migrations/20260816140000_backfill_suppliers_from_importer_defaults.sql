insert into public.suppliers (
    importer_id,
    name,
    eta_days,
    pick_up_location,
    freight_forwarder,
    order_frequency,
    notes,
    trucking_cost_per_bottle,
    active
)
select
    importer_id,
    name,
    eta_days,
    pick_up_location,
    freight_forwarder,
    order_frequency,
    notes,
    trucking_cost_per_bottle,
    true
from importer_defaults
on conflict (name) do update
set
    importer_id = coalesce(nullif(public.suppliers.importer_id, ''), excluded.importer_id),
    eta_days = case when coalesce(public.suppliers.eta_days, 0) > 0 then public.suppliers.eta_days else excluded.eta_days end,
    pick_up_location = coalesce(nullif(public.suppliers.pick_up_location, ''), excluded.pick_up_location),
    freight_forwarder = coalesce(nullif(public.suppliers.freight_forwarder, ''), excluded.freight_forwarder),
    order_frequency = coalesce(nullif(public.suppliers.order_frequency, ''), excluded.order_frequency),
    notes = coalesce(nullif(public.suppliers.notes, ''), excluded.notes),
    trucking_cost_per_bottle = case
        when coalesce(public.suppliers.trucking_cost_per_bottle, 0) > 0 then public.suppliers.trucking_cost_per_bottle
        else excluded.trucking_cost_per_bottle
    end,
    active = coalesce(public.suppliers.active, true),
    updated_at = now();

select public.refresh_vinosmith_wine_stem_laid_in();
